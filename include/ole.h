/* How a new object is shown. */
typedef enum { olerender_none, olerender_draw, olerender_format } OLEOPT_RENDER;

/* When a link is brought up to date. */
typedef enum {
  oleupdate_always,
  oleupdate_onsave,
  oleupdate_oncall,
  oleupdate_onclose
} OLEOPT_UPDATE;

/* OleRegisterServer: one instance serves all documents, or one each. */
