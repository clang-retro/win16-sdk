/* ole.h: OLE 1.0, object linking and embedding for Windows 3.1 (OLECLI.DLL
 * for container programs, OLESVR.DLL for server programs). Written for
 * clang-dos from the published API; AGPL-3.0-only, see the win16-sdk
 * LICENSE.
 *
 * Objects, clients, streams, servers and server documents are structures
 * whose first member is a far pointer to a table of CALLBACK functions. The
 * program fills the tables of the structures it gives to OLE. */
