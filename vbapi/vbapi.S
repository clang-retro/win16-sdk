/* VBGetVersion: the version of Visual Basic (VB300_VERSION and the
 * others). When the offset of the dispatcher is 0x00BC, the stub gives
 * VB100_VERSION and does not call function 47, as Microsoft's VBAPI.LIB
 * does: Visual Basic 1.0 does not have that function. */
    .globl VBGETVERSION
VBGETVERSION:
    cmpw $0x00bc, %ss:0x20
    je 1f
    jmp __VBGETVERSION_STUB
1:
    movw $0x0100, %ax
    lretw
