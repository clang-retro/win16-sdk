/* vbapi.S: the stubs of the Visual Basic API functions (vbapi.h), for
 * custom controls (VBX) and DLLs that Visual Basic loads.
 * Written for clang-retro; AGPL-3.0-only, see the win16-sdk LICENSE.
 *
 * The functions are not exports of a module. Visual Basic puts a far
 * pointer to its dispatcher at offset 0x20 of its stack segment, and the
 * code of a DLL runs on that stack. Each stub puts 4 times the number of
 * its function in BX and jumps to the dispatcher, with the arguments of
 * the caller still on the stack. The names are in upper case, as FAR
 * PASCAL makes them. */

/* VBSTUB name, number: a stub for function number of the dispatcher. */
.macro VBSTUB name, number
    .globl \name
\name:
    movw $(\number * 4), %bx
    ljmpw *%ss:0x20
.endm

